r"""Reproduce M0-M7 evidence using the lab's original CLI entry points.

Run from src with .\.venv\Scripts\python.exe scripts/check_lab9.py.
Reports are generated by lab9.eval. Expected gate failures are verified as failures.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile


def trace_evidence(source: Path) -> None:
    """Run the supplied bug switches on fresh stores for trace-backed taxonomy evidence."""
    sys.path.insert(0, str(source))
    from lab8.shapes import SHAPES
    from lab9.eval import load_spec, load_world, make_task
    from lab9.variant_agent import make_shape

    world, claims = load_world(load_spec())
    labels = {claim["claim_id"]: claim["expected"] for claim in claims}
    cases = [("leaky_trace", "C-001"), ("ignore_denied", "C-007"), ("ticket_trust", "C-002"),
             ("sum_parts", "C-014"), ("pre_deducted", "C-014"), ("stale_clause", "C-006"),
             ("sibling_refund", "C-001"), ("misreport", "C-008"),
             ("no_override", "C-005"), ("no_override", "C-004")]
    evidence = []
    with tempfile.TemporaryDirectory(prefix="lab9-taxonomy-", ignore_cleanup_errors=True) as tmp:
        for bug, claim_id in cases:
            for variant, switches in ((bug, {"no_override", bug}), ("fixed", {"no_override"})):
                name = f"evidence_{variant}"
                SHAPES[name] = make_shape(name, switches)
                try:
                    trial = make_task(name, world, claims, labels, Path(tmp))({"claim_id": claim_id, "seed": 11})
                finally:
                    SHAPES.pop(name)
                evidence.append({"bug": bug, "control": variant == "fixed", "claim_id": claim_id,
                                 "seed": 11, "label": labels[claim_id], "trial": trial})
    (source / "reports/trace_evidence.json").write_text(
        json.dumps(evidence, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(evidence)} trace trials to reports/trace_evidence.json", flush=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-tests", action="store_true")
    parser.add_argument("--trace-only", action="store_true")
    parser.add_argument("--tests-only", action="store_true")
    args = parser.parse_args()
    source = Path(__file__).resolve().parents[1]
    os.chdir(source)
    evidence = source / "reports/checkpoints.json"
    evidence.parent.mkdir(parents=True, exist_ok=True)
    if args.trace_only:
        trace_evidence(source)
        return 0
    env = {**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8"}
    checks = []

    def run(module: str, *arguments: str, expected: int = 0, contains: str = "") -> None:
        command = [sys.executable, "-m", module, *arguments]
        print(f"Running {' '.join(command[2:])}", flush=True)
        result = subprocess.run(command, cwd=source, env=env, capture_output=True, text=True, encoding="utf-8")
        output = result.stdout + result.stderr
        print(output, end="", flush=True)
        passed = result.returncode == expected and contains in output
        checks.append({"command": command[1:], "expected_exit": expected, "exit": result.returncode,
                       "passed": passed, "output": output})
        evidence.write_text(json.dumps({"checks": checks, "passed": all(c["passed"] for c in checks)},
                                       ensure_ascii=False, indent=2), encoding="utf-8")
        if not passed:
            raise RuntimeError(f"unexpected result from {module}, expected exit {expected}")

    if args.tests_only:
        previous = json.loads(evidence.read_text(encoding="utf-8")) if evidence.exists() else {"checks": []}
        checks.extend(check for check in previous["checks"] if check["command"][1] != "pytest")
        run("pytest", "-q")
        run("pytest", "-q", "-m", "student", "-o", "addopts=", "-k", "lab9")
        return 0
    run("lab9.smoke", contains="M0 PASS")
    run("lab9.evalset", "--build", "--check", contains="0 problem(s)")
    run("lab9.evalset", "--v2", "--build", contains="0 problem(s)")
    if not args.skip_tests:
        run("pytest", "-q")
        run("pytest", "-q", "-m", "student", "-o", "addopts=", "-k", "lab9")
    run("lab9.judge", "--csv", "data/eval/judge_tone_public.csv", "--audit", "5", contains="PASS floors")
    run("lab9.judge", "--csv", "data/eval/judge_helpful_public.csv", "--audit", "5", expected=1, contains="FAIL floors")
    for shape, filename in (("swarm", "baseline_v1"), ("swarm", "eval_pr"),
                            ("fixed", "eval_fixed"), ("seeded_regression", "eval_seeded_regression")):
        run("lab9.eval", "--shape", shape, "--out", f"reports/{filename}.json")
        run("lab9.gate", "--pr", f"reports/{filename}.json", "--baseline", "reports/baseline_v1.json",
            expected=1 if shape == "seeded_regression" else 0,
            contains="pass_rate" if shape == "seeded_regression" else "exit 0")
    run("lab9.ci_check", "--pr", "reports/eval_pr.json", "--baseline", "reports/baseline_v1.json")
    run("lab9.mutation", "--detect")
    spec = "config/metric_spec_v2.yaml"
    run("lab9.eval", "--shape", "swarm", "--spec", spec, "--out", "reports/baseline_v2.json")
    run("lab9.gate", "--pr", "reports/baseline_v2.json", "--baseline", "reports/baseline_v2.json", "--spec", spec)
    run("lab9.mutation", "--spec", spec, "--baseline", "reports/baseline_v2.json", contains="mutation score 3/3")
    run("lab9.mutation", "--spec", spec, "--aa", "66,77,88,99,110")
    run("lab9.eval", "--shape", "slice_regression", "--spec", spec, "--out", "reports/eval_slice_regression.json")
    run("lab9.gate", "--pr", "reports/eval_slice_regression.json", "--baseline", "reports/baseline_v2.json",
        "--spec", spec, expected=1, contains="slice:money_movement/pass_rate")
    run("lab9.traps", "--pr", "reports/eval_slice_regression.json", "--baseline", "reports/baseline_v2.json", "--spec", spec)
    for trap in ("evaluator_errors_as_nan", "dropped_failing_rows", "cherry_picked_seeds", "loosened_spec"):
        trap_spec = f"reports/traps/{trap}.spec.yaml" if trap == "loosened_spec" else spec
        run("lab9.gate", "--pr", f"reports/traps/{trap}.json", "--baseline", "reports/baseline_v2.json",
            "--spec", trap_spec, "--base-spec", spec, expected=1, contains="INTEGRITY")
    trace_evidence(source)
    print(f"Verified {len(checks)} checkpoint commands. Evidence {evidence}")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
